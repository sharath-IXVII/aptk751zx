"""Part 4: YouTube title, description, tags and thumbnail.

Thumbnail background: NVIDIA image model (FLUX) if it works, otherwise a frame from the video.
Then big bold text is drawn on top with Pillow.
"""

import base64
import io
import logging
import os
import subprocess
import textwrap
from pathlib import Path

import httpx
from PIL import Image, ImageDraw, ImageEnhance, ImageFont

from pipeline import llm

log = logging.getLogger(__name__)

IMAGE_URL = os.getenv("NVIDIA_IMAGE_URL",
                      "https://ai.api.nvidia.com/v1/genai/black-forest-labs/flux.1-dev")
FONT_PATHS = ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
              "C:/Windows/Fonts/arialbd.ttf", "/Library/Fonts/Arial Bold.ttf"]
SIZE = (1280, 720)


def make_metadata(script: dict) -> dict:
    """Ask the LLM for YouTube title, description, tags, thumbnail text and image prompt."""
    meta = llm.chat_json(f"""Create YouTube metadata for this video. The channel posts positive,
uplifting explainers for Indian and US viewers.

VIDEO SCRIPT TITLE: {script["title"]}
VIDEO SCRIPT:
{script["script"]}

Rules:
- title: max 70 characters, curiosity-driven but honest (no clickbait lies), no emojis
- description: 2 short paragraphs summarising the video (no hashtags, no links)
- tags: 12-15 relevant search tags
- thumbnail_text: 2-4 punchy words in CAPITALS for the thumbnail
- image_prompt: a vivid, cinematic, photorealistic scene for the thumbnail background,
  no text or letters in the image, no real people's faces

Return JSON: {{"title": "...", "description": "...", "tags": ["..."],
"thumbnail_text": "...", "image_prompt": "..."}}""", temperature=0.6, max_tokens=2000)

    sources = "\n".join(f"- {s['source'] or 'Source'}: {s['url']}"
                        for s in script.get("sources", [])[:5])
    meta["description"] = (
        f"{meta['description'].strip()}\n\nSources:\n{sources}\n\n"
        "This video was created with the help of AI tools (script and visuals)."
    )[:4900]
    meta["title"] = meta["title"].strip()[:100]
    tags, total = [], 0
    for tag in meta.get("tags", []):  # YouTube limit: ~500 characters of tags
        tag = str(tag).strip().replace("<", "").replace(">", "")
        if tag and total + len(tag) + 2 < 480:
            tags.append(tag)
            total += len(tag) + 2
    meta["tags"] = tags
    return meta


def _ai_background(prompt: str) -> Image.Image | None:
    key = os.getenv("NVIDIA_API_KEY")
    if not key:
        return None
    for width, height in ((1344, 768), (1024, 1024)):
        try:
            resp = httpx.post(IMAGE_URL, timeout=180,
                              headers={"Authorization": f"Bearer {key}", "Accept": "application/json"},
                              json={"prompt": prompt, "width": width, "height": height,
                                    "steps": 30, "cfg_scale": 3.5, "seed": 0, "mode": "base"})
            if resp.status_code >= 400:
                log.warning("Image model HTTP %s: %s", resp.status_code, resp.text[:200])
                continue
            data = resp.json()
            b64 = (data.get("artifacts") or [{}])[0].get("base64") or data.get("image")
            if b64:
                log.info("Thumbnail background generated by AI (%dx%d)", width, height)
                return Image.open(io.BytesIO(base64.b64decode(b64))).convert("RGB")
        except Exception as exc:
            log.warning("Image model failed: %s", exc)
    return None


def _video_frame(video: Path) -> Image.Image:
    out = video.with_name("frame.jpg")
    duration = float(subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
         str(video)], capture_output=True, text=True).stdout.strip() or 10)
    subprocess.run(["ffmpeg", "-y", "-v", "error", "-ss", str(duration * 0.3), "-i", str(video),
                    "-frames:v", "1", str(out)], check=True)
    log.info("Thumbnail background taken from the video")
    return Image.open(out).convert("RGB")


def _cover(img: Image.Image) -> Image.Image:
    """Scale and crop to 1280x720."""
    scale = max(SIZE[0] / img.width, SIZE[1] / img.height)
    img = img.resize((round(img.width * scale), round(img.height * scale)), Image.LANCZOS)
    left, top = (img.width - SIZE[0]) // 2, (img.height - SIZE[1]) // 2
    return img.crop((left, top, left + SIZE[0], top + SIZE[1]))


def _font(size: int) -> ImageFont.FreeTypeFont:
    for path in FONT_PATHS:
        if Path(path).exists():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default(size)


def make_thumbnail(meta: dict, video: Path, out: Path) -> Path:
    bg = _ai_background(meta.get("image_prompt", meta["title"])) or _video_frame(video)
    # Clean, professional look: slightly muted photo, soft dark fade, white text only.
    img = ImageEnhance.Color(_cover(bg)).enhance(0.85)
    img = ImageEnhance.Brightness(img).enhance(0.9)

    shade = Image.new("L", SIZE)
    shade.putdata([int(215 * max(0.0, 1 - x / (SIZE[0] * 0.7)) ** 1.4)
                   for _ in range(SIZE[1]) for x in range(SIZE[0])])
    img.paste(Image.new("RGB", SIZE, (8, 10, 14)), (0, 0), shade)

    text = meta.get("thumbnail_text", "").upper().strip() or meta["title"].upper()
    lines = textwrap.wrap(text, width=14)[:3]
    draw = ImageDraw.Draw(img)
    size = 108 if len(lines) <= 2 else 88
    font = _font(size)
    line_h = int(size * 1.12)
    y = (SIZE[1] - len(lines) * line_h) // 2
    x = 72
    draw.rectangle((x, y - 34, x + 120, y - 26), fill="white")  # thin accent line
    for line in lines:
        # Soft shadow instead of a thick outline.
        draw.text((x + 3, y + 4), line, font=font, fill=(0, 0, 0))
        draw.text((x, y), line, font=font, fill="white")
        y += line_h

    out.parent.mkdir(parents=True, exist_ok=True)
    img.save(out, "JPEG", quality=90)
    if out.stat().st_size > 2_000_000:  # YouTube limit is 2 MB
        img.save(out, "JPEG", quality=75)
    log.info("Thumbnail saved to %s", out)
    return out
